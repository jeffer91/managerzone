const assert=require('assert');
const base=require('../src/engine.js');
const spatial=require('../src/spatial-engine.js');
spatial.install(base);
const make=(uid,a)=>{const p={uid,name:uid,age:24,...a};p.ratings=base.ratePlayer(p);return p;};
const center={role:'DEL',x:50,y:15},wide={role:'DEL',x:18,y:22};
const finisher=make('finisher',{rem:10,pa:4,ctrl:7,ve:7,intel:7,ca:7,exp:6,res:6,en:2,at:1,pl:2});
const creator=make('creator',{rem:8,pa:9,ctrl:9,ve:9,intel:8,ca:3,exp:5,res:7,en:2,at:1,pl:6});
assert(base.slotRating(finisher,center,[center,wide])>base.slotRating(creator,center,[center,wide]),'el DC debe premiar más el remate');
assert(base.slotRating(creator,wide,[center,wide])>base.slotRating(finisher,wide,[center,wide]),'el delantero abierto debe valorar pase/control/velocidad sin dejar de valorar remate');
const dm={role:'VOL',x:50,y:60},am={role:'VOL',x:50,y:38},wm={role:'VOL',x:18,y:49};
const organizer=make('organizer',{pa:10,ctrl:10,intel:9,res:7,en:4,rem:7,ve:6,pl:6,at:1,ca:3,exp:6});
const runner=make('runner',{pa:7,ctrl:7,intel:6,res:9,en:6,rem:5,ve:10,pl:7,at:1,ca:3,exp:5});
assert(base.slotRating(organizer,am,[dm,am,wm])>base.slotRating(runner,am,[dm,am,wm]),'el mejor creador debe ser fuerte en el centro adelantado');
assert(base.slotRating(runner,wm,[dm,am,wm])>base.slotRating(runner,am,[dm,am,wm])-.5,'la banda debe aprovechar velocidad y pase');
const right=make('right',{pa:8,ctrl:8,intel:7,res:7,en:7,rem:5,ve:8,pl:8,foot:'Diestro'});right.heightCm=183;
const md={role:'VOL',x:83,y:49},mi={role:'VOL',x:17,y:49};
assert(base.slotRating(right,md,[md,mi])>base.slotRating(right,mi,[md,mi]),'el pie dominante debe influir ligeramente en la banda natural');
assert.equal(base.slotCode(dm,[dm,am,wm]),'MCD');
assert.equal(base.slotCode(am,[dm,am,wm]),'MCO');
assert.equal(base.slotCode(wide,[center,wide]),'EI');
assert(spatial.penaltyScore(finisher,center)>spatial.penaltyScore(organizer,am),'penales deben favorecer delanteros/rematadores');
console.log('✓ Continuous spatial engine, foot preference and set-piece priorities OK');